def preview_media(config: dict) -> dict:
    """Return per-type / total estimates without going near the
    warehouse. Mirrors ``demo_documents.preview_documents``.
    """
    types = config.get("types") or []
    counts = config.get("counts") or {}
    per_type = []
    total_files = 0
    total_bytes = 0
    total_seconds = 0.0
    unknown: list[str] = []
    for t in types:
        if t not in MEDIA_TYPES:
            unknown.append(t)
            continue
        n = int(counts.get(t, 5))
        bytes_each = _AVG_BYTES_PER_TYPE.get(t, 50_000)
        per_sec = _GEN_PER_SECOND_PER_TYPE.get(t, 100)
        per_type.append(
            {
                "type": t,
                "category": MEDIA_TYPES[t]["category"],
                "label": MEDIA_TYPES[t]["label"],
                "count": n,
                "estimated_bytes": n * bytes_each,
                "estimated_seconds": round(n / per_sec, 1),
            }
        )
        total_files += n
        total_bytes += n * bytes_each
        total_seconds += n / per_sec
    return {
        "per_type": per_type,
        "total_files": total_files,
        "total_bytes": total_bytes,
        "estimated_seconds": round(total_seconds, 1),
        "unknown_types": unknown,
    }
