# ── Lazy import probe ──────────────────────────────────────────────
#
# Mirrors `src.demo_documents.is_available()` — the router gates on
# this before dispatch and surfaces a clean 503 with an install hint
# when the [media] extra isn't installed.

MEDIA_AVAILABLE: bool = False
_UNAVAILABLE_REASON: str | None = (
    "The `[media]` optional extra is not installed. Run "
    "`pip install clone-xs[media]` (which pulls Pillow) and restart "
    "the API server. The video_clip type also requires the `ffmpeg` "
    "system binary on PATH — install with Homebrew (`brew install "
    "ffmpeg`) or apt (`apt-get install ffmpeg`)."
)
try:
    import importlib.util as _ilutil

    if _ilutil.find_spec("PIL") is not None:
        MEDIA_AVAILABLE = True
        _UNAVAILABLE_REASON = None
except Exception as _e:  # pragma: no cover — defensive
    _UNAVAILABLE_REASON = f"media deps probe failed: {_e}"


def is_available() -> tuple[bool, str | None]:
    """Return ``(available, reason)``. The router uses this to render
    a calm install-hint banner when Pillow is missing."""
    return MEDIA_AVAILABLE, _UNAVAILABLE_REASON


def _ffmpeg_available() -> tuple[bool, str | None]:
    """Per-tick probe for ffmpeg. Distinct from Pillow because ffmpeg
    is a system binary that may be missing even when Pillow is
    installed. The video_clip generator uses this to fail cleanly
    without aborting other types."""
    if shutil.which("ffmpeg"):
        return True, None
    return False, (
        "`ffmpeg` is not on PATH — required for the video_clip media "
        "type only. Install with `brew install ffmpeg` (macOS) or "
        "`apt-get install ffmpeg` (Linux). Other media types work "
        "without it."
    )


