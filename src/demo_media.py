"""Synthetic media generators for the /demo-data Media tab.

Pairs with `src.demo_documents` — same registry / orchestrator /
destination-radio pattern, different output shapes:

  - **Images** (PNG): synthesised in Pillow from gradients + noise +
    geometric primitives. No bundled assets — everything is generated
    from scratch so the repo doesn't carry license-bound binary blobs.
  - **Audio** (WAV): synthesised via stdlib `wave` (sine waves at
    voice frequencies + white noise). Operator gets a Faker-generated
    transcript as the file's "voicemail message" text in the metadata.
  - **Video** (MP4): generated by shelling out to ffmpeg's `lavfi`
    test-pattern source (no input files needed). When ffmpeg isn't on
    PATH, the type fails cleanly with an install hint while every
    other type continues.

Why pure synthesis instead of bundled assets:

  - The repo doesn't have to track / license / re-distribute binary
    blobs (audio clips, photos, X-ray samples).
  - The synthesis is fast (~5 ms per image, ~50 ms per WAV, ~500 ms
    per MP4 clip) and produces files that are clearly demo-shaped.
  - Operators get reproducible output by passing `faker_seed`.

Architecture is identical to demo_documents:

    DOCUMENT_TYPES → MEDIA_TYPES (same shape)
    is_available() probes Pillow at module-import time
    generate_media() is the orchestrator with the same destination radio
"""

